const gcdExtended=(left,right)=>{
    let oldR=Math.abs(left)
    let currentR=Math.abs(right)
    let oldS=1
    let currentS=0
    let oldT=0
    let currentT=1
    while(currentR!==0){
        const quotient=Math.floor(oldR/currentR)
        ;[oldR,currentR]=[currentR,oldR-quotient*currentR]
        ;[oldS,currentS]=[currentS,oldS-quotient*currentS]
        ;[oldT,currentT]=[currentT,oldT-quotient*currentT]
    }
    return {
        gcd:oldR,
        left:left<0?-oldS:oldS,
        right:right<0?-oldT:oldT
    }
}

const swapColumns=(matrix,left,right)=>{
    if(left===right){
        return
    }
    for(const row of matrix){
        ;[row[left],row[right]]=[row[right],row[left]]
    }
}

const combineColumns=(matrix,pivotColumn,otherColumn,pivotFactor,otherFactor,gcd,pivotValue,otherValue)=>{
    for(const row of matrix){
        const pivot=row[pivotColumn]
        const other=row[otherColumn]
        row[pivotColumn]=pivotFactor*pivot+otherFactor*other
        row[otherColumn]=(-otherValue/gcd)*pivot+(pivotValue/gcd)*other
    }
}

/* Build an integer basis for the column lattice generated by an m x n matrix.
   Elementary unimodular column operations preserve that lattice. Pivots are
   collected bottom-up so each later reduction leaves prior coordinates fixed. */
export function columnLatticeBasis(matrix){
    if(!Array.isArray(matrix)||matrix.length===0||!Array.isArray(matrix[0])){
        throw new TypeError("matrix must be a non-empty rectangular array")
    }
    const columns=matrix[0].length
    if(columns===0||matrix.some(row=>!Array.isArray(row)||row.length!==columns)){
        throw new TypeError("matrix must be rectangular and have at least one column")
    }
    if(matrix.some(row=>row.some(value=>!Number.isSafeInteger(value)))){
        throw new TypeError("matrix entries must be safe integers")
    }
    const work=matrix.map(row=>[...row])
    let active=columns
    const pivots=[]
    for(let rowIndex=work.length-1;rowIndex>=0&&active>0;rowIndex--){
        let candidate=-1
        for(let column=0;column<active;column++){
            if(work[rowIndex][column]!==0){
                candidate=column
                break
            }
        }
        if(candidate<0){
            continue
        }
        const pivotColumn=active-1
        swapColumns(work,candidate,pivotColumn)
        for(let column=0;column<pivotColumn;column++){
            const other=work[rowIndex][column]
            if(other===0){
                continue
            }
            const pivot=work[rowIndex][pivotColumn]
            const {gcd,left,right}=gcdExtended(pivot,other)
            combineColumns(work,pivotColumn,column,left,right,gcd,pivot,other)
        }
        if(work[rowIndex][pivotColumn]<0){
            for(const values of work){
                values[pivotColumn]=-values[pivotColumn]
            }
        }
        pivots.push({row:rowIndex,column:pivotColumn,value:work[rowIndex][pivotColumn]})
        active--
    }
    return {
        dimension:work.length,
        basis:work.map(row=>row.slice(active)),
        pivots:pivots.map(({row,column,value})=>({row,column:column-active,value}))
    }
}

/* Return the canonical representative of v modulo the column lattice. */
export function quotientRepresentative(vector,lattice){
    if(!Array.isArray(vector)||vector.length!==lattice.dimension||
       vector.some(value=>!Number.isSafeInteger(value))){
        throw new TypeError("vector must contain one safe integer per lattice dimension")
    }
    const result=[...vector]
    for(const {row,column,value} of lattice.pivots){
        const quotient=Math.floor(result[row]/value)
        if(quotient===0){
            continue
        }
        for(let index=0;index<lattice.dimension;index++){
            result[index]-=quotient*lattice.basis[index][column]
        }
    }
    return result
}
